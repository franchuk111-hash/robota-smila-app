export type LandingSeo = CatSeo & {
  slug: string;
  filter: (v: Vacancy) => boolean;
};

// Українські відмінки для кількості вакансій: 5 → «5 актуальних вакансій».
export function vacancyCountLabel(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return `${n} актуальна вакансія`;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return `${n} актуальні вакансії`;
  return `${n} актуальних вакансій`;
}

// Сама лише іменникова форма — для заголовків, де число вже стоїть окремо:
// «1 вакансія», «3 вакансії», «7 вакансій».
export function vacancyNoun(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return "вакансія";
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return "вакансії";
  return "вакансій";
}

// Заголовок категорійної сторінки з числом і роком. Число в title помітно
// відображає фактичну кількість пропозицій у добірці.
export function categoryTitle(h1: string, count: number, year = 2026): string {
  if (count <= 0) return `${h1} — вакансії ${year}`;
  return `${h1} — ${count} ${vacancyNoun(count)} ${year}`;
}

// Заголовок лендінга з фактичною кількістю вакансій і роком.
export function landingTitle(h1: string, count: number, year = 2026): string {
  if (count <= 0) return `${h1} — вакансії ${year}`;
  return `${h1} — ${count} ${vacancyNoun(count)} ${year}`;
}

