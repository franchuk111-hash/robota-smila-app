import assert from 'node:assert/strict';
import { ALL_VACANCIES, getActiveVacancies } from '../lib/data';
import { isListedVacancy } from '../lib/vacancy-lifecycle';
import { vacancyCategory } from '../lib/vacancy-category';
import sitemap from '../app/sitemap';
const now = Date.parse('2026-09-30T19:00:00Z');
const old = ALL_VACANCIES.find(v => v.id === 1040)!;
assert.ok(old); assert.equal(isListedVacancy(old, now), false);
assert.ok(!getActiveVacancies(now).some(v => v.id === 1040));
assert.ok(!sitemap().some(item => item.url.endsWith('/vakansiya/1040')));
const fresh = { ...old, date: '2026-09-25' };
assert.equal(isListedVacancy(fresh, now), true);
assert.equal(isListedVacancy({ ...fresh, validThrough: '2026-09-29' }, now), false);
assert.equal(isListedVacancy({ ...fresh, date: '2026-10-01' }, now), false);
assert.equal(isListedVacancy({ ...fresh, date: 'invalid' }, now), false);
assert.equal(isListedVacancy({ ...fresh, date: '2026-08-31' }, now), false);
assert.equal(isListedVacancy({ ...fresh, date: '2026-08-31', validThrough: '2026-10-01' }, now), true);
assert.equal(vacancyCategory('Вантажник-приймальник', 'торгівля').cat, 'robitnyk');
assert.equal(vacancyCategory('Менеджер з продажу B2B', 'торгівля').cat, 'office');
assert.equal(vacancyCategory('Продавець-касир', 'торгівля').cat, 'prodavets');
assert.equal(vacancyCategory('Водій', 'торгівля').cat, 'voditel');
console.log(`PASS lifecycle/taxonomy: ${getActiveVacancies(now).length} listed / ${ALL_VACANCIES.length} total; archived URL retained.`);
